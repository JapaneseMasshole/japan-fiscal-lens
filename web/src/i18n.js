// For non-string messages (e.g. lists).
export function tm(key) {
  return key.split('.').reduce((obj, k) => obj?.[k], messages[locale.value])
}

export function t(key, vars = {}) {
  const msg = key.split('.').reduce((obj, k) => obj?.[k], messages[locale.value]) ?? key
  return msg.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`)
}
